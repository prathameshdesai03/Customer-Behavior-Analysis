-- Database creation and setup
CREATE DATABASE Customer_Behavior;
USE Customer_Behavior;

-- View raw data
SELECT * FROM customer;
SELECT * FROM Transactions;
SELECT * FROM prod_cat_info;

-- Disable safe update mode to allow modifications
SET SQL_SAFE_UPDATES = 0;

-- Convert string dates to standard SQL DATE format
UPDATE customer 
SET DOB = STR_TO_DATE(REPLACE(DOB, '/', '-'), '%d-%m-%Y');

UPDATE Transactions
SET tran_date = STR_TO_DATE(REPLACE(tran_date, '/', '-'), '%d-%m-%Y');

-- Re-assign primary key and update column data types
ALTER TABLE customer
    DROP PRIMARY KEY,
    MODIFY customer_Id INT NOT NULL,
    MODIFY Gender VARCHAR(1),
    MODIFY DOB DATE,
    MODIFY city_code INT NOT NULL,
    ADD PRIMARY KEY (customer_Id);

-- 1. Total row count across tables
SELECT COUNT(*) AS TOT_Rows FROM customer;
SELECT COUNT(*) AS TOT_Rows FROM prod_cat_info;
SELECT COUNT(*) AS TOT_Rows FROM Transactions;

-- 2. Total return transactions and return value
SELECT 
    COUNT(*) AS Total_Return_Orders,
    ROUND(SUM(total_amt), 2) AS Total_Return_Cost
FROM Transactions 
WHERE total_amt < 0;

-- 3. Transaction time window span
SELECT 
    MIN(tran_date) AS start_date,
    MAX(tran_date) AS end_date,
    DATEDIFF(MAX(tran_date), MIN(tran_date)) AS total_days,
    TIMESTAMPDIFF(MONTH, MIN(tran_date), MAX(tran_date)) AS total_months,
    TIMESTAMPDIFF(YEAR, MIN(tran_date), MAX(tran_date)) AS total_years
FROM Transactions;

-- 4. Category of the subcategory 'DIY'
SELECT prod_cat 
FROM prod_cat_info
WHERE prod_subcat = 'DIY';

-- 5. Store type with highest transactions
SELECT 
    Store_type,
    COUNT(Store_type) AS Total_count_store_type 
FROM Transactions
GROUP BY Store_type
ORDER BY COUNT(Store_type) DESC
LIMIT 1;

-- 6. Customer demographic breakdown by gender
SELECT 
    SUM(CASE WHEN Gender = 'M' THEN 1 ELSE 0 END) AS Total_Male_Persons,
    SUM(CASE WHEN Gender = 'F' THEN 1 ELSE 0 END) AS Total_Female_Persons
FROM customer;

-- 7. City with maximum customer concentration
SELECT 
    city_code,
    COUNT(city_code) AS Total_customers
FROM customer
GROUP BY city_code
ORDER BY COUNT(city_code) DESC
LIMIT 1;

-- 8. Subcategories under 'Books'
SELECT prod_subcat
FROM prod_cat_info
WHERE prod_cat = 'books';

-- 9. Maximum quantity in a single order
SELECT Qty AS maximum_quantity_ordered_in_a_single_transaction 
FROM transactions
ORDER BY Qty DESC
LIMIT 1;

-- 10. Revenue generated by Electronics and Books
SELECT 
    p.prod_cat AS Category,
    ROUND(SUM(t.total_amt), 2) AS Total_revenue
FROM transactions t
INNER JOIN prod_cat_info p
    ON t.prod_cat_code = p.prod_cat_code
   AND t.prod_subcat_code = p.prod_sub_cat_code
WHERE p.prod_cat IN ('Electronics', 'Books')
GROUP BY p.prod_cat
ORDER BY ROUND(SUM(t.total_amt), 2) DESC;

-- 11. High-frequency customers (>= 11 valid transactions)
SELECT 
    cust_id,
    COUNT(DISTINCT transaction_id) AS total_valid_transactions
FROM Transactions
WHERE total_amt > 0
GROUP BY cust_id
HAVING COUNT(DISTINCT transaction_id) >= 11
ORDER BY total_valid_transactions DESC;

-- 12. Combined revenue from Clothing and Electronics in Flagship stores
SELECT 
    ROUND(SUM(t.total_amt), 2) AS Total_Revenue
FROM transactions t
JOIN prod_cat_info p
    ON p.prod_cat_code = t.prod_cat_code 
   AND p.prod_sub_cat_code = t.prod_subcat_code
WHERE p.prod_cat IN ('Clothing', 'Electronics') 
  AND t.Store_type = 'Flagship store';

-- 13. Male customers' revenue in Electronics by subcategory
SELECT 
    p.prod_subcat AS sub_category,
    ROUND(SUM(t.total_amt), 2) AS total_revenue
FROM Transactions t
INNER JOIN customer c 
    ON t.cust_id = c.customer_Id
INNER JOIN prod_cat_info p 
    ON t.prod_cat_code = p.prod_cat_code 
   AND t.prod_subcat_code = p.prod_sub_cat_code
WHERE Gender = 'M' AND prod_cat = 'Electronics'
GROUP BY p.prod_subcat
ORDER BY ROUND(SUM(t.total_amt), 2) DESC;

-- 14. Top 5 subcategories by sales along with returns and return rate percentage
SELECT 
    p.prod_subcat AS sub_category,
    ROUND(SUM(CASE WHEN t.total_amt > 0 THEN t.total_amt ELSE 0 END), 2) AS total_sales,
    ROUND(SUM(CASE WHEN t.total_amt < 0 THEN ABS(t.total_amt) ELSE 0 END), 2) AS total_returns,
    ROUND(
        (SUM(CASE WHEN t.total_amt < 0 THEN ABS(t.total_amt) ELSE 0 END) / 
         NULLIF(SUM(CASE WHEN t.total_amt > 0 THEN t.total_amt ELSE 0 END), 0)) * 100, 
        2
    ) AS return_rate_percentage
FROM Transactions t
INNER JOIN prod_cat_info p 
    ON t.prod_cat_code = p.prod_cat_code 
   AND t.prod_subcat_code = p.prod_sub_cat_code
GROUP BY p.prod_subcat
ORDER BY total_sales DESC
LIMIT 5;

-- 15. Revenue from customers aged 25 to 35 in the last 30 days of transactions
SELECT 
    ROUND(SUM(t.total_amt), 2) AS total_revenue
FROM Transactions t
INNER JOIN customer c 
    ON t.cust_id = c.customer_Id
WHERE 
    TIMESTAMPDIFF(YEAR, c.DOB, '2026-09-11') BETWEEN 25 AND 35
    AND t.tran_date >= (
        SELECT MAX(tran_date) - INTERVAL 30 DAY
        FROM Transactions
    );

-- 16. Category with highest return value in the final 3 months
SELECT 
    p.prod_cat AS product_category,
    ROUND(-SUM(t.total_amt), 2) AS total_return_value
FROM Transactions t
INNER JOIN prod_cat_info p 
    ON t.prod_cat_code = p.prod_cat_code 
   AND t.prod_subcat_code = p.prod_sub_cat_code
WHERE t.total_amt <= 0
  AND t.tran_date >= (
        SELECT MAX(tran_date) - INTERVAL 3 MONTH 
        FROM transactions
  )
GROUP BY p.prod_cat
ORDER BY ROUND(-SUM(t.total_amt), 2) DESC
LIMIT 1;

-- 17. Store type generating maximum sales and quantity
SELECT 
    Store_type,
    COUNT(qty) AS Total_Quantity,
    ROUND(SUM(total_amt), 2) AS Total_sales
FROM transactions
GROUP BY Store_type
ORDER BY ROUND(SUM(total_amt), 2) DESC, COUNT(qty) DESC
LIMIT 1;

-- 18. Product categories with average revenue above overall mean
SELECT 
    p.prod_cat,
    ROUND(AVG(t.total_amt), 2) AS Total_avg_Revenue
FROM transactions t
INNER JOIN prod_cat_info p
    ON t.prod_cat_code = p.prod_cat_code 
   AND t.prod_subcat_code = p.prod_sub_cat_code
GROUP BY p.prod_cat
HAVING ROUND(AVG(t.total_amt), 2) > (SELECT ROUND(AVG(total_amt), 2) FROM transactions)
ORDER BY ROUND(AVG(t.total_amt), 2) DESC;

-- 19. Top 5 categories by transaction volume and average revenue
SELECT 
    p.prod_cat,
    ROUND(AVG(t.total_amt), 2) AS Average_Revenue,
    ROUND(SUM(t.total_amt), 2) AS Total_Revenue,
    COUNT(t.QTY) AS Total_Count
FROM transactions t
INNER JOIN prod_cat_info p
    ON t.prod_cat_code = p.prod_cat_code
   AND t.prod_subcat_code = p.prod_sub_cat_code
GROUP BY p.prod_cat
ORDER BY Total_Count DESC, Average_Revenue DESC
LIMIT 5;